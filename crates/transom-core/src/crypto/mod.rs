//! 同步与备份的加密封装：TSYN 二进制信封与 JSON/YAML 内嵌信封。
//!
//! 设计原理（Why）：两种信封都是"文档落在不可信介质"（公开 S3 桶、私有
//! Git 仓库、导出的备份文件）上的线格式契约，被网络传输层（云同步/Git
//! 同步）、存储层（备份读写）共用。此前实现放在存储层，导致 net 反向依赖
//! store——网络层为了加解密 API 拖进整套 JSON 存储、钥匙串与文件 IO 实现。
//! 上提到契约层后依赖方向恢复为 core <- {net, store}。
//!
//! 代价与局限：core 因此新增 argon2 / chacha20poly1305 / base64 / getrandom
//! 四条加密依赖；工作区全部消费者本就通过传递依赖编译它们，实际编译单元
//! 不增加，但"领域模型 crate"的依赖面比纯模型更宽，属有意的取舍。

